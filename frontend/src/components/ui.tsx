/* ------------------------------------------------------------------ chips */
type ChipKind = 'synthetic' | 'illustrative' | 'estimated' | 'green' | 'yellow' | 'red' | 'blue' | 'ghost'
const CHIP_ICON: Partial<Record<ChipKind, IconName>> = {
  synthetic: 'flask', illustrative: 'info', estimated: 'spark',
  green: 'check', yellow: 'alert', red: 'alert', blue: 'info',
}

/** The honesty label every number-bearing panel carries (SPEC §9). */
export function TruthLabel({ kind = 'estimated' }: { kind?: 'synthetic' | 'illustrative' | 'estimated' }) {
  const text = { synthetic: 'Synthetic', illustrative: 'Illustrative', estimated: 'Estimated' }[kind]
  const title = {
    synthetic: 'Generated by the ProfitPilot simulator — no real seller or Meesho data',
    illustrative: 'An input assumption for the prototype, not a measured cost',
    estimated: 'Model output with an uncertainty range — not a guarantee',
  }[kind]
  return <Chip kind={kind} title={title}>{text}</Chip>
}

export function Chip({ kind = 'ghost', children, title, icon }: { kind?: ChipKind; children: ReactNode; title?: string; icon?: IconName }) {
  const ic = icon ?? CHIP_ICON[kind]
  return (
    <span className={`chip chip-${kind}`} title={title}>
      {ic ? <Icon name={ic} /> : null}
      {children}
    </span>
  )
}

export function ConfidencePill({ label, block, compact = false }: { label: Confidence; block?: { n_eff: number; band_width: number; extrapolation_pct: number; rule: string }; compact?: boolean }) {
  const kind = label === 'High' ? 'green' : label === 'Medium' ? 'yellow' : 'red'
  const title = block
    ? `Rule — ${block.rule}\nComparable weight (n_eff): ${num(block.n_eff, 0)}\nRange width: ${pct(block.band_width, 0)}\n${
        block.extrapolation_pct > 0 ? `Outside the observed price range by ${pct(block.extrapolation_pct, 0)}` : 'Inside the observed price range'
      }`
    : 'Confidence reflects comparable evidence, range width and model calibration'
  return (
    <Chip kind={kind} title={title}>
      {label} confidence{compact ? '' : ' ★'}
    </Chip>
  )
}

export function StatusPill({ status }: { status: StatusPillT }) {
  const kind = status.id === 'losing' ? 'red' : status.id === 'watch' ? 'yellow' : 'green'
  const icon: IconName = status.icon === 'alert' ? 'alert' : status.icon === 'eye' ? 'eye' : 'check'
  return <Chip kind={kind} icon={icon}>{status.label}</Chip>
}

/* ------------------------------------------------------------------ numbers */
export function RangeNumber({ value, format = (v: number) => inr(v), size = 'lg', tone = '' }: {
  value: Band
  format?: (v: number) => string
  size?: 'lg' | 'sm'
  tone?: '' | 'good' | 'bad'
}) {
  return (
    <div className={`metric ${tone === 'good' ? 'metric-good' : tone === 'bad' ? 'metric-bad' : 'metric-primary'}`}>
      <div className={`value ${size === 'sm' ? 'sm' : ''}`}>{format(value.p50)}</div>
      <div className="range">range {format(value.p10)} – {format(value.p90)}</div>
    </div>
  )
}

export function MetricBlock({ label, value, format, note, tone, size = 'sm' }: {
  label: string
  value: Band | number
  format?: (v: number) => string
  note?: string
  tone?: '' | 'good' | 'bad'
  size?: 'lg' | 'sm'
}) {
  const f = format ?? ((v: number) => inr(v))
  const band: Band = typeof value === 'number' ? { p10: value, p50: value, p90: value } : value
  return (
    <div className="metric">
      <div className="label">{label}</div>
      <div className={`value ${size === 'sm' ? 'sm' : ''} ${tone === 'good' ? 'metric-good' : tone === 'bad' ? 'metric-bad' : ''}`}>
        {f(band.p50)}
      </div>
      <div className="range">{typeof value === 'number' ? (note ?? '') : `range ${f(band.p10)} – ${f(band.p90)}`}</div>
    </div>
  )
}

