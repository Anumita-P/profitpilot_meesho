/* ------------------------------------------------------------------ constraints */
export function ConstraintList({ constraints, limit = 9 }: { constraints: Constraint[]; limit?: number }) {
  return (
    <div>
      {constraints.slice(0, limit).map((c) => (
        <div key={c.id} data-constraint={c.id} data-pass={String(c.pass_)} className="row-tight"
          style={{ justifyContent: 'space-between', padding: '6px 0', borderBottom: '1px dashed var(--line)' }}>
          <span className="row-tight small">
            <Icon name={c.pass_ ? 'check' : 'alert'} color={c.pass_ ? '#15803d' : '#b91c1c'} />
            {c.label}
            {c.note ? <span className="tiny muted">· {c.note}</span> : null}
          </span>
          <span className={`small ${c.pass_ ? 'muted' : ''}`} style={{ color: c.pass_ ? undefined : 'var(--red-700)' }}>
            {c.unit === 'share' ? `${pct(c.actual)} vs ${pct(c.required)} cap` :
             c.unit === '₹/kept order' ? `${inr(c.actual)} vs ${inr(c.required)} floor` :
             c.unit === 'orders/day' ? `${num(c.actual, 1)} vs ${num(c.required, 0)}/day floor` :
             c.unit === '₹' ? `${inr(c.actual)} (limit ${inr(c.required)})` :
             c.unit === 'units' ? `${num(c.actual, 0)} vs ${num(c.required, 0)} needed` :
             c.pass_ ? 'passes' : 'fails'}
          </span>
        </div>
      ))}
    </div>
  )
}

export function ConstraintChipRow({ constraints }: { constraints: Record<string, boolean> }) {
  const FAIL_LABEL: Record<string, string> = {
    contribution_floor: 'contribution floor', volume_floor: 'volume floor', return_cap: 'return cap',
    corridor: 'market corridor', max_price_move: '12% step cap', confidence: 'confidence',
    inventory: 'inventory cover', cash: 'working capital',
  }
  return (
    <div className="pill-row">
      {Object.entries(constraints).map(([k, ok]) => (
        <Chip key={k} kind={ok ? 'green' : 'red'} title={ok ? 'passed at this price' : 'failed at this price'}>
          {FAIL_LABEL[k] ?? k}: {ok ? 'passes' : 'fails'}
        </Chip>
      ))}
    </div>
  )
}

